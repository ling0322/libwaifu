/// The length regulator, which turns one vector per semantic token into one per mel frame.
///
/// Its own test because it is its own module in the reference, and because the resize in the
/// middle of it is the one place a gather had to be written as a matrix — see
/// `nearest_selection`. Nine tokens onto twenty-four frames is deliberately not a whole ratio, so
/// that a resize which only handles integer scaling would be caught.
#[test]
fn the_length_regulator_is_the_reference_regulator() {
    let config = s2mel::RegulatorConfig {
        in_channels: REGULATOR_IN,
        channels: REGULATOR_CHANNELS,
        out_channels: REGULATOR_CHANNELS,
        stages: REGULATOR_STAGES,
    };

    let tokens = tensor("tokens", &[1, TOKENS, REGULATOR_IN]);
    let selection = s2mel::nearest_selection(TOKENS, FRAMES, CPU).unwrap();

    let g = Graph::new();
    let out = s2mel::length_regulator(
        &g,
        g.input("tokens"),
        g.input("selection"),
        &config,
        FRAMES,
        F32,
        CPU,
    )
    .unwrap();
    g.output("out", out);

    let filled = Filled;
    let ir = Ir::compile(&g, Residency::Device);
    let preloaded = ir.load(&filled).unwrap();
    let outputs = ir
        .run(
            &RunContext::new(&filled)
                .preloaded(&preloaded)
                .input("tokens", &tokens)
                .input("selection", &selection),
        )
        .unwrap();

    let result = outputs[0].1.to_device(CPU).unwrap();
    assert_eq!(result.shape(), vec![1, FRAMES, REGULATOR_CHANNELS]);

    let got = result.to_vec_f32().unwrap();
    let indices = probe_indices(got.len(), REGULATED.len());
    let sampled: Vec<f32> = indices.iter().map(|index| got[*index]).collect();

    close(&sampled, &REGULATED, 2e-3, "regulated");
}

/// `mish` is written without a logarithm; this is that identity, against the definition.
///
/// `x * tanh(softplus(x))` with `softplus(x) = ln(1 + exp(x))`, computed here in f64 straight
/// from the definition, against the exp-only form the graph uses.
#[test]
fn mish_is_the_activation_it_replaces() {
    let values: Vec<f32> = (-40..=40).map(|i| i as f32 * 0.25).collect();
    let x = Tensor::from_f32(&[1, 1, values.len() as i32], &values).unwrap();

    let g = Graph::new();
    let out = s2mel::mish(&g, g.input("x"), F32, CPU).unwrap();
    g.output("out", out);

    let filled = Filled;
    let ir = Ir::compile(&g, Residency::Device);
    let preloaded = ir.load(&filled).unwrap();
    let outputs = ir
        .run(
            &RunContext::new(&filled)
                .preloaded(&preloaded)
                .input("x", &x),
        )
        .unwrap();
    let got = outputs[0].1.to_device(CPU).unwrap().to_vec_f32().unwrap();

    let want: Vec<f32> = values
        .iter()
        .map(|v| {
            let v = *v as f64;
            (v * (1.0 + v.exp()).ln().tanh()) as f32
        })
        .collect();

    close(&got, &want, 1e-5, "mish");
}

