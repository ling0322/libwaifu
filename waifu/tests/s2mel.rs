/// The Euler solver, against an integral that can be done by hand.
///
/// The network is replaced by a constant velocity field, which makes the whole trajectory exact:
/// `steps` steps of `1 / steps` each add up to one unit of time, so whatever the field says is
/// added exactly once. Checking arithmetic against a closed form rather than against a recorded
/// number is what makes this say the loop is right and not merely unchanged.
#[test]
fn the_solver_integrates_a_constant_velocity_exactly() {
    let channels = 3;
    let frames = 8;
    let prompt_len = 3;

    let z = tensor("z", &[1, channels, frames]);
    let prompt = tensor("prompt", &[1, channels, prompt_len]);
    let velocity: Vec<f32> = (0..channels * frames)
        .map(|i| 0.25 + i as f32 * 0.01)
        .collect();

    for steps in [1, 4, 7] {
        let field = Tensor::from_f32(&[1, channels, frames], &velocity).unwrap();
        let out = s2mel::solve_euler(&z, &prompt, prompt_len, steps, 0.0, |_, _, _, _| {
            Ok(field.clone())
        })
        .unwrap();

        let got = out.to_device(CPU).unwrap().to_vec_f32().unwrap();
        let start = z.to_vec_f32().unwrap();

        for row in 0..channels as usize {
            for frame in 0..frames as usize {
                let index = row * frames as usize + frame;

                // The prompt's own frames are held at zero throughout, never integrated.
                let want = match frame < prompt_len as usize {
                    true => 0.0,
                    false => start[index] + velocity[index],
                };

                assert!(
                    (got[index] - want).abs() < 1e-5,
                    "{steps} steps, row {row} frame {frame}: {} is not {want}",
                    got[index]
                );
            }
        }
    }
}

/// Guidance combines the two passes the way the reference combines them, and asks for the second
/// one only when the rate is above zero.
#[test]
fn guidance_is_two_passes_combined() {
    let (channels, frames, prompt_len) = (2, 6, 2);
    let rate = 0.7f32;

    let z = tensor("z", &[1, channels, frames]);
    let prompt = tensor("prompt", &[1, channels, prompt_len]);

    let conditioned = vec![0.5f32; (channels * frames) as usize];
    let free = vec![0.2f32; (channels * frames) as usize];

    let mut asked = Vec::new();
    let out = s2mel::solve_euler(
        &z,
        &prompt,
        prompt_len,
        1,
        rate,
        |_, prompt_x, _, guided| {
            asked.push(guided);

            // The unguided pass is handed a prompt of zeros; the guided one the real thing.
            let held = prompt_x.to_vec_f32().unwrap();
            let empty = held.iter().all(|value| *value == 0.0);
            assert_eq!(empty, !guided, "the wrong prompt went to the {guided} pass");

            Ok(Tensor::from_f32(
                &[1, channels, frames],
                match guided {
                    true => &conditioned,
                    false => &free,
                },
            )
            .unwrap())
        },
    )
    .unwrap();

    assert_eq!(
        asked,
        vec![true, false],
        "one guided pass then one free one"
    );

    let got = out.to_device(CPU).unwrap().to_vec_f32().unwrap();
    let start = z.to_vec_f32().unwrap();
    let combined = (1.0 + rate) * 0.5 - rate * 0.2;

    for row in 0..channels as usize {
        for frame in prompt_len as usize..frames as usize {
            let index = row * frames as usize + frame;
            let want = start[index] + combined;

            assert!(
                (got[index] - want).abs() < 1e-5,
                "row {row} frame {frame}: {} is not {want}",
                got[index]
            );
        }
    }
}

/// With the rate at zero there is one pass and no second one, which is what makes guidance
/// something you pay for rather than something you always pay for.
#[test]
fn no_guidance_is_one_pass() {
    let (channels, frames) = (2, 4);

    let z = tensor("z", &[1, channels, frames]);
    let prompt = tensor("prompt", &[1, channels, 1]);

    let mut passes = 0;
    let field = Tensor::from_f32(
        &[1, channels, frames],
        &vec![0.1f32; (channels * frames) as usize],
    )
    .unwrap();

    s2mel::solve_euler(&z, &prompt, 1, 3, 0.0, |_, _, _, guided| {
        passes += 1;
        assert!(guided, "an unguided pass was asked for at a rate of zero");

        Ok(field.clone())
    })
    .unwrap();

    assert_eq!(passes, 3, "three steps, one pass each");
}
