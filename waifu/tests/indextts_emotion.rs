fn hash32(name: &str) -> u32 {
    let mut value: u32 = 0x811c_9dc5;
    for byte in name.bytes() {
        value = (value ^ u32::from(byte)).wrapping_mul(0x0100_0193);
    }

    value
}

/// `count` numbers in `[-scale, scale]`, drawn by xorshift from `name`.
///
/// Scattered rather than swept: see the note at the top of this file.
fn scatter(name: &str, count: usize, scale: f64) -> Vec<f32> {
    let mut state = hash32(name) | 1;

    (0..count)
        .map(|_| {
            state ^= state << 13;
            state ^= state >> 17;
            state ^= state << 5;

            ((f64::from(state) / f64::from(u32::MAX) * 2.0 - 1.0) * scale) as f32
        })
        .collect()
}

struct Scattered;

impl ParamSource for Scattered {
    fn load(&self, name: &str, shape: &[i32]) -> Result<Tensor> {
        let count: usize = shape.iter().map(|size| *size as usize).product();

        Ok(Tensor::from_f32(
            shape,
            &scatter(name, count, WEIGHT_SCALE),
        )?)
    }

    fn shape_of(&self, _: &str) -> Option<Vec<i32>> {
        None
    }

    fn has(&self, _: &str) -> bool {
        true
    }

    fn check(&self, _: &str, _: &[i32]) -> Result<()> {
        Ok(())
    }
}

fn probe_indices(length: usize, limit: usize) -> Vec<usize> {
    let step = (length / limit).max(1);

    (0..limit).map(|i| (i * step + i * 7) % length).collect()
}

fn probe(tensor: &Tensor) -> (Vec<i32>, Vec<f32>) {
    let values = tensor.to_vec_f32().unwrap();
    let indices = probe_indices(values.len(), 8);

    (
        tensor.shape(),
        indices.iter().map(|index| values[*index]).collect(),
    )
}

fn close(got: &[f32], want: &[f32], what: &str) {
    for (index, (left, right)) in got.iter().zip(want).enumerate() {
        assert!(
            (left - right).abs() <= TOLERANCE,
            "{what}[{index}]: {left} against {right}",
        );
    }
}

fn features() -> Tensor {
    Tensor::from_f32(
        &[1, FRAMES, INPUT_DIM],
        &scatter("features", (FRAMES * INPUT_DIM) as usize, INPUT_SCALE),
    )
    .unwrap()
}

/// Build a graph around `stage`, run it over the same recording, and sample what comes out.
///
/// The position table is an input rather than a constant, the way the model takes it, so every
/// probe below reads the one [`emotion::positional_encoding`] built -- which is itself
/// the first thing checked.
/// Where the conformer's weights live, which is where a probe of one stage has to look for them.
///
/// The names a parameter source is handed are the checkpoint's whole names, and a stage run on
/// its own at the root would ask for `embed.conv.0.weight` where the reference drew
/// `emo_conditioning_encoder.embed.conv.0.weight`. Same shapes, different numbers, and every
/// probe below would fail for that reason rather than its own.
fn encoder_namespace(g: &Graph) -> Graph {
    g.subgraph("emo_conditioning_encoder")
}

fn perceiver_namespace(g: &Graph) -> Graph {
    g.subgraph("emo_perceiver_encoder")
}

fn run(stage: impl Fn(&Graph, Value, &Config, Value) -> Value) -> (Vec<i32>, Vec<f32>) {
    let config = config();
    let positions =
        emotion::positional_encoding(Config::subsampled(FRAMES), ENCODER_DIM, CPU)
            .unwrap();

    let g = Graph::new();
    let out = stage(&g, g.input("x"), &config, g.input("positions"));
    g.output("out", out);

    let weights = Scattered;
    let ir = Ir::compile(&g);
    let outputs = ir
        .run(
            &RunContext::new(&weights)
                .input("x", &features())
                .input("positions", &positions),
        )
        .unwrap();

    probe(&outputs[0].1.to_device(CPU).unwrap())
}

/// The table both sides build for themselves. A disagreement here is the formula, and every
/// probe after it would fail for a reason that is not its own.
#[test]
fn builds_the_sinusoid_table_upstream_carries() {
    let table = emotion::positional_encoding(Config::subsampled(FRAMES), ENCODER_DIM, CPU)
        .unwrap();

    let (shape, got) = probe(&table);

    assert_eq!(shape, vec![1, Config::subsampled(FRAMES), ENCODER_DIM]);
    close(&got, &POSITIONS, "positions");
}

/// `Conv2dSubsampling2` and the projection over what it flattens, times `xscale`.
///
/// Also the one place the subsampled length is asserted outright: a convolution at stride two
/// with no padding leaves `(T - 3) / 2 + 1` frames and not `T / 2`, and the two differ for every
/// length.
#[test]
fn embeds_the_recording_the_way_the_subsampling_does() {
    let (shape, got) = run(|g, x, config, _| {
        emotion::embed(&encoder_namespace(g).subgraph("embed"), x, config, FRAMES)
    });

    assert_eq!(shape, vec![1, 10, ENCODER_DIM]);
    assert_eq!(Config::subsampled(FRAMES), 10);
    close(&got, &EMBEDDED, "embedded");
}

/// The whole conformer: the blocks, their relative attention, and `after_norm`.
#[test]
fn reads_the_recording_the_way_the_conformer_does() {
    let (shape, got) = run(|g, x, config, positions| {
        emotion::encoder(
            &encoder_namespace(g),
            x,
            config,
            FRAMES,
            positions,
            F32,
            CPU,
        )
        .unwrap()
    });

    assert_eq!(shape, vec![1, 10, ENCODER_DIM]);
    close(&got, &ENCODED, "encoded");
}

/// The perceiver on its own, fed the conformer's output.
///
/// One latent in and one latent out, which is what makes the stage after it a vector rather than
/// a sequence.
#[test]
fn boils_the_recording_down_the_way_the_perceiver_does() {
    let (shape, got) = run(|g, x, config, positions| {
        let encoded = emotion::encoder(
            &encoder_namespace(g),
            x,
            config,
            FRAMES,
            positions,
            F32,
            CPU,
        )
        .unwrap();

        emotion::perceiver(
            &perceiver_namespace(g),
            encoded,
            config,
            Config::subsampled(FRAMES),
            F32,
            CPU,
        )
    });

    assert_eq!(shape, vec![1, LATENTS, LATENT_DIM]);
    close(&got, &RESAMPLED, "resampled");
}

/// All four stages, which is what `Gpt::prefill` is handed.
#[test]
fn produces_the_emotion_row_the_gpt_takes() {
    let (shape, got) = run(|g, x, config, positions| {
        emotion::graph(g, x, config, FRAMES, positions, F32, CPU).unwrap()
    });

    assert_eq!(shape, vec![1, MODEL_DIM]);
    close(&got, &EMOTION, "emotion");
}

/// The emotion row is the width the GPT's prefix wants, at the real configuration rather than
/// this file's cut one.
///
/// A shape rather than a number, and worth its own test: every probe above runs a model whose
/// widths were chosen to be quick, and the one thing they cannot check is that the released
/// widths fit together. `model_dim` here and `gpt::Config::indextts().model_dim` are two
/// constants that have to agree, and nothing else compares them.
#[test]
fn releases_a_row_as_wide_as_the_gpt_is() {
    let emotion = Config::indextts();
    let gpt = waifu::indextts::gpt::Config::indextts();

    assert_eq!(emotion.model_dim, gpt.model_dim);
    assert_eq!(emotion.input_dim, 1024);
    assert_eq!(emotion.latents, 1);
}
