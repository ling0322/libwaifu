// The reference constants below are machine-written by `tools/indextts_emotion_reference.py` at
// f32's own precision.
#![allow(clippy::excessive_precision)]

//! IndexTTS-2.5's emotion path against the released source's own conformer and perceiver.
//!
//! No download and no checkpoint: `ConformerEncoder` and `PerceiverResampler` are imported from
//! the tree cached under `~/.cache/libwaifu/indextts-src` and run. Regenerate with:
//!
//! ```text
//! .venv/bin/python tools/indextts_emotion_reference.py
//! ```
//!
//! Why the reference is upstream's code rather than a second reading of the paper: a WeNet
//! conformer has several places where a reimplementation can be self-consistently wrong and still
//! produce a tensor of the right shape -- whether `rel_shift` is applied, which half of a gated
//! unit is the gate, whether the feed forward is halved for macaron style, whether the position
//! table is added to the input or only to the scores. None of those is visible in a shape, and
//! none would be caught by comparing this against a description of what it should do.
//!
//! # The weights scatter, and that is the point
//!
//! Every other reference here sweeps a sine per parameter. This draws by xorshift instead,
//! because most of what this module does is attention: a swept parameter makes every key in a
//! projection point nearly the same way, the softmax over them comes out flat, and a flat softmax
//! is an average -- which does not care what order its keys arrived in. `docs/indextts_gpt.md`
//! has the longer version, and the bug it cost.
//!
//! # Four probes and a table
//!
//! `positions` is the sinusoid table, which nothing learned and both sides build for themselves
//! -- so a disagreement there is the formula, before any weight is involved. The other four cut
//! the model where upstream itself cuts it: after `self.embed`, after the blocks, after the
//! perceiver, and after the two projections. A failure says which.
//!
//! # Verified by mutation, and the scale is why
//!
//! Nine plausible bugs were written into the module one at a time, and every one of them fails
//! here by between 55 and 11,000 times the tolerance: the gate taken from the wrong half of
//! either gated unit, the feed forward halved as though this conformer were macaron style (it is
//! not -- [`waifu::indextts::w2v_bert`]'s is, which is exactly how that mistake would arrive), the position
//! term dropped from the scores, `pos_bias_v` used where `pos_bias_u` belongs, the depthwise
//! convolution made causal, `norm_conv` and `norm_ff` swapped, `xscale` left off, and the
//! perceiver's latents left out of what they read.
//!
//! **The weight scale had to be raised to get there.** At the 0.25 the other reference scripts
//! here use, activations land where GELU is still nearly a straight line, `gelu(a) * b` and
//! `gelu(b) * a` come out within a thousandth of each other, and the end-to-end probe did not
//! notice the halves being swapped at all. Drawing at 0.7 puts the activations at the order of
//! one, which is where the released model runs and where its nonlinearities are nonlinear.
//!
//! One thing that is *not* a bug, and looked like one: concatenating the context the other way
//! round, `cat(context, latents)`, changes nothing. It permutes the keys and the values together
//! and a softmax does not care -- which holds only because there is no mask and no position
//! encoding in the perceiver's attention. Upstream's `emo_cond_mask_pad` prepends the latent's
//! own `True` at position zero, so the order would matter the moment a batch were padded.

